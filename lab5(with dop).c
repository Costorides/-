#include <stdio.h>
#define N 10

// проверка на равенство после отзеркаливания
int you_are_me(int x1[], int x2[]) {
    for(int i = 0; i < N; i++) {
        if(x1[i] != x2[i])
            return 0;
    }
    return 1;
}

// функция "меняем местами"
void swap(int *a, int *b) {
    int temp = *a; //temp получает значение по адресу a
    *a = *b; //в ячейку по адресу а записывается значение из ячейки по адресу b
    *b = temp; //ну тут и так понятно
}
// Возвращает индекс опорного элемента после разделения
int partition(int x1[], int low, int high) {
    // Выбираем опорный элемент (возьмём последний)
    int pivo = x1[high];

    // Индекс для меньшего элемента
    int i = low - 1;

    // Проходим по всем элементам от low до high-1
    for(int j = low; j < high; j++) {
        // Если текущий элемент меньше или равен опорному
        if(x1[j] <= pivo) {
            i++;  // увеличиваем индекс меньших элементов
            swap(&x1[i], &x1[j]);  // меняем местами
        }
    }

    // Помещаем опорный элемент на правильное место
    swap(&x1[i + 1], &x1[high]);

    // Возвращаем индекс опорного элемента
    return i + 1;
}

// Рекурсивная функция быстрой сортировки
void qsort(int x1[], int low, int high) {
    if(low < high) {
        // Получаем индекс опорного элемента
        int pivo = partition(x1, low, high);

        // Рекурсивно сортируем левую часть
        qsort(x1, low, pivo - 1);

        // Рекурсивно сортируем правую часть
        qsort(x1, pivo + 1, high);
    }
}

